"""Regenerate llms-full.txt: the project documentation concatenated into one file for LLMs.

Run after editing README.md, docs/*.md or AGENTS.md:   python scripts/build_llms_full.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ["README.md", "docs/ARCHITECTURE.md", "docs/API.md", "docs/PADDLE_VEHICLE.md", "AGENTS.md"]

HEADER = """# Data Capture Tool - full documentation (generated by scripts/build_llms_full.py)

Local Flask + plain-JS app that captures one clean training image per vehicle from live RTSP streams inside
user-drawn ROIs. This file concatenates: {names}. Source files: backend/ (Python), frontend/ (static UI).
"""


def build() -> str:
    parts = [HEADER.format(names=", ".join(SOURCES))]
    for name in SOURCES:
        text = (ROOT / name).read_text(encoding="utf-8").strip()
        parts.append(f"\n\n{'=' * 78}\n# FILE: {name}\n{'=' * 78}\n\n{text}\n")
    return "".join(parts)


if __name__ == "__main__":
    out = ROOT / "llms-full.txt"
    out.write_text(build(), encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes)")
